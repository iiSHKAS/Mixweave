"""Regenerate the explicit local audio API registry after command signature changes."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Intentionally excludes application lifecycle, arbitrary file dialogs, updates,
# backups, shortcuts and virtual-device teardown/init.
MODULES = ['apps', 'buses', 'channels', 'channel_test', 'devices', 'eq', 'hardware', 'mic', 'profiles', 'routing', 'settings', 'profile_automation']
EXCLUDE = {'init_virtual_devices', 'teardown_virtual_devices', 'export_channel_eq_to_file', 'import_eq_file'}
SETTINGS = {'get_backend_info', 'get_prefs', 'set_device_label_style', 'set_meter_mode', 'set_multiple_mics', 'set_balance_visible', 'set_balance_channels', 'get_default_devices', 'set_default_output', 'set_default_input'}
registry = []
arms = []
for module in MODULES:
    module_path = f'commands/{module}' if module != 'profile_automation' else module
    rust_path = module_path.replace('/', '::')
    source = (ROOT / f'src-tauri/src/{module_path}.rs').read_text()
    for match in re.finditer(r'#\[tauri::command\]\s*pub (async )?fn (\w+)\((.*?)\)\s*->\s*(.*?)\s*\{', source, re.S):
        asynchronous, name, args, returns = match.groups()
        if asynchronous or name in EXCLUDE or (module == 'settings' and name not in SETTINGS):
            continue
        # Parameters here are separated by commas except inside generic types.
        parts = re.split(r',\s*(?![^<]*>)', args.strip().rstrip(',')) if args.strip() else []
        params, calls = [], []
        for part in parts:
            key, typ = part.strip().split(':', 1)
            key, typ = key.removeprefix('mut ').strip(), typ.strip()
            if key in ('state', 'runtime'):
                calls.append('app.state()')
            elif key == 'app':
                calls.append('app.clone()')
            else:
                optional = typ.startswith('Option<')
                params.append({'name': key, 'type': typ, 'required': not optional})
                calls.append(f'arg(&params, "{key}")?')
        read_only = name.startswith(('get_', 'list_', 'export_', 'import_'))
        registry.append({'method': name, 'group': module, 'read_only': read_only, 'params': params})
        call = f'crate::{rust_path}::{name}({", ".join(calls)})'
        if returns.startswith('Result<'):
            call += '.map_err(ApiError::command)?'
        arms.append(f'        "{name}" => serde_json::to_value({call}),')
output = '''// Generated by scripts/api/generate_registry.py; do not edit manually.
use serde_json::Value;
use tauri::Manager;
use super::{arg, ApiError};
pub fn dispatch(app: &tauri::AppHandle, method: &str, params: Value) -> Result<Value, ApiError> {
    let result = match method {
''' + '\n'.join(arms) + '''
        _ => return Err(ApiError::unknown_method()),
    };
    result.map_err(|e| ApiError::internal(e.to_string()))
}
'''
(ROOT / 'src-tauri/src/local_api/registry.rs').write_text(output)
(ROOT / 'src-tauri/src/local_api/commands.json').write_text(json.dumps(registry, indent=2) + '\n')
print(f'Generated {len(registry)} API commands')
